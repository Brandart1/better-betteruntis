// Generates test/sync/e2e_vectors_v2.json from lib/sync/e2e_crypto.dart with
// fixed "random" bytes, and prints Argon2id timings.
//
//   dart run tool/e2e_vectors/generate.dart          # writes the JSON
//   node tool/e2e_vectors/verify.mjs                 # independent cross-check
//
// The vectors are checked by test/sync/e2e_crypto_test.dart (Dart) and by
// verify.mjs (independent @noble implementations).
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:better_betteruntis/sync/e2e_crypto.dart';
import 'package:cryptography/cryptography.dart';

Future<List<int>> hkdf(List<int> ikm, String info) async {
  final k = await Hkdf(
    hmac: Hmac.sha256(),
    outputLength: 32,
  ).deriveKey(secretKey: SecretKey(ikm), info: utf8.encode(info));
  return k.extractBytes();
}

Uint8List hex(String s) => Uint8List.fromList([
  for (var i = 0; i < s.length; i += 2)
    int.parse(s.substring(i, i + 2), radix: 16),
]);

String toHex(List<int> b) =>
    b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

/// Fixed bytes: byte i of a [length]-byte value = (start + i * step) & 0xff.
Uint8List pattern(int start, int length, [int step = 1]) => Uint8List.fromList([
  for (var i = 0; i < length; i++) (start + i * step) & 0xff,
]);

/// Returns the given values in order; each call must ask for the next length.
E2eRandomBytes queue(List<Uint8List> values) {
  var i = 0;
  return (n) {
    final v = values[i++];
    if (v.length != n) throw StateError('expected $n bytes, have ${v.length}');
    return v;
  };
}

Future<void> main() async {
  const passphrase = 'correct horse battery staple';
  const passphrase2 = 'Pässwört ✓ 🔐 测试';
  final salt = pattern(0x00, 16);
  final dek = pattern(0x10, 32);
  final wrapNonce = pattern(0x40, 24);
  final checkNonce = pattern(0x60, 24);
  final recoveryKey = pattern(0x80, 16, 7);
  final recNonce = pattern(0xa0, 24);
  final salt2 = pattern(0xf0, 16);
  final wrapNonce2 = pattern(0xc0, 24, 3);

  final sw = Stopwatch()..start();
  final setup = await createE2e(
    passphrase,
    withRecovery: true,
    random: queue([salt, dek, wrapNonce, checkNonce, recoveryKey, recNonce]),
  );
  stderr.writeln('createE2e (1 Argon2id): ${sw.elapsedMilliseconds} ms');
  final keys = setup.keys;
  final header = setup.header;

  final kdfCases = <Map<String, Object?>>[];
  for (final (p, s) in [(passphrase, salt), (passphrase2, salt2)]) {
    sw.reset();
    final kek = await deriveKek(p, E2eKdfParams(salt: s));
    stderr.writeln('Argon2id m=19456 t=2 p=1: ${sw.elapsedMilliseconds} ms');
    kdfCases.add({
      'passphrase': p,
      'salt': toHex(s),
      'm': e2eDefaultMemoryKiB,
      't': e2eDefaultIterations,
      'p': e2eDefaultParallelism,
      'kek': toHex(kek),
    });
  }

  final header2 = await changePassphrase(
    header,
    keys,
    passphrase2,
    random: queue([salt2, wrapNonce2]),
  );

  final noteKeys = [
    '2026-11-17|3|MATH',
    '2026-11-18|1|D',
    'Mathe – Ü1 🧮 数学',
    '',
  ];
  final serverKeys = [
    for (final k in noteKeys)
      {'noteKey': k, 'serverKey': await serverKey(keys, k)},
  ];

  final longText = List.filled(20, 'Schularbeit über Übungen 📐 – ').join();
  final notes = <Map<String, Object?>>[];
  // (noteKey, exam, text, updatedAt, deleted)
  final noteInputs = <(String, bool, String, int, bool)>[
    // exam note
    ('2026-11-17|3|MATH', true, 'Schularbeit Kapitel 4', 1763370000123, false),
    // tombstone
    ('2026-11-18|1|D', false, '', 1763456400000, true),
    // unicode key and long unicode text
    ('Mathe – Ü1 🧮 数学', false, longText, 1763000000001, false),
    // used = 8 + 14 + 234 = 256: exactly one block
    ('2026-11-18|1|D', true, 'x' * 234, 0, false),
    // used = 257: two blocks; updatedAt = 2^53 - 1 (high u32 half used)
    ('2026-11-18|1|D', false, 'y' * 235, 9007199254740991, false),
  ];
  for (var i = 0; i < noteInputs.length; i++) {
    final (k, exam, text, updatedAt, deleted) = noteInputs[i];
    final nonce = pattern(0x11 * (i + 1), 24, 5);
    final blob = await encryptNote(
      keys,
      noteKey: k,
      exam: exam,
      text: text,
      updatedAt: updatedAt,
      deleted: deleted,
      random: queue([nonce]),
    );
    final plain = encodeNotePlaintext(noteKey: k, exam: exam, text: text);
    final sk = await serverKey(keys, k);
    notes.add({
      'noteKey': k,
      'exam': exam,
      'text': text,
      'updatedAt': updatedAt,
      'deleted': deleted,
      'nonce': toHex(nonce),
      'serverKey': sk,
      'aad': toHex(
        noteAad(serverKey: sk, updatedAt: updatedAt, deleted: deleted),
      ),
      'paddedLength': plain.length,
      'plaintext': toHex(plain),
      'blob': blob,
    });
  }

  final vectors = {
    'description':
        'BetterBetterUntis E2E test vectors (header v1, note blob v2). Hex for raw bytes; '
        'wire strings (header fields, serverKey, blob) are base64url without '
        'padding. Generated by tool/e2e_vectors/generate.dart, verified '
        'independently by tool/e2e_vectors/verify.mjs.',
    'constants': {
      'infoNoteKey': 'bbu-note-key-v1',
      'infoNoteEnc': 'bbu-note-enc-v1',
      'infoCheck': 'bbu-check-v1',
      'infoRecoveryKek': 'bbu-recovery-kek-v1',
      'infoHeaderAuth': 'bbu-header-auth-v1',
      'headerBoxVersion': e2eVersion,
      'noteBlobVersion': e2eNoteBlobVersion,
      'aadDekWrap': 'bbu-dek-wrap-v1',
      'aadCheck': 'bbu-check-v1',
      'checkPlaintext': 'bbu-e2e-check-v1',
      'padBlock': e2ePadBlock,
    },
    'kdf': kdfCases,
    'setup': {
      'passphrase': passphrase,
      'random': {
        'salt': toHex(salt),
        'dek': toHex(dek),
        'wrapNonce': toHex(wrapNonce),
        'checkNonce': toHex(checkNonce),
        'recoveryKey': toHex(recoveryKey),
        'recoveryNonce': toHex(recNonce),
      },
      'kek': kdfCases[0]['kek'],
      // HKDF-SHA256 subkeys (computed here directly with package:cryptography).
      'subkeys': {
        'noteKey': toHex(await hkdf(dek, 'bbu-note-key-v1')),
        'noteEnc': toHex(await hkdf(dek, 'bbu-note-enc-v1')),
        'check': toHex(await hkdf(dek, 'bbu-check-v1')),
        'recoveryKek': toHex(await hkdf(recoveryKey, 'bbu-recovery-kek-v1')),
        'authKey': toHex(await hkdf(dek, 'bbu-header-auth-v1')),
      },
      'authKeyB64': keys.authKeyB64,
      'authHashB64': keys.authHashB64,
      'recoveryCode': setup.recoveryCode,
      'header': header.toJson(),
    },
    'changePassphrase': {
      'newPassphrase': passphrase2,
      'random': {'salt': toHex(salt2), 'wrapNonce': toHex(wrapNonce2)},
      'header': header2.toJson(),
    },
    'serverKeys': serverKeys,
    'notes': notes,
  };
  final out = File('test/sync/e2e_vectors_v2.json');
  out.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(vectors)}\n',
  );
  stdout.writeln('wrote ${out.path}');
}
